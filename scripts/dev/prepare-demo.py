"""Prepare pinned demo dependencies in an isolated directory; start no services.

Only the invoking oracle checkout is installed from source. External Python
packages come from PyPI or an exact upstream Git commit. Dependency checkouts
provide demo configuration, schema data, and Solidity sources, never ambient
editable imports from a developer's workspace.
"""

from __future__ import annotations

import argparse
import json
import shlex
import shutil
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

ORACLE_ROOT = Path(__file__).resolve().parents[2]
DEPENDENCY_MANIFEST = Path(__file__).with_name("demo-dependencies.json")


def git_output(directory: Path, *arguments: str) -> str:
    """Read one Git fact from the explicitly selected checkout."""
    return subprocess.check_output(
        ["git", "-C", str(directory), *arguments], text=True
    ).strip()


def prepare_checkout(directory: Path, *, url: str, commit: str) -> None:
    """Create a pinned checkout or reuse the exact clean one; never reset it."""
    if directory.exists():
        if not (directory / ".git").exists():
            raise ValueError(f"dependency directory is not a checkout: {directory}")
        if git_output(directory, "remote", "get-url", "origin") != url:
            raise ValueError(f"dependency origin differs: {directory}")
        if git_output(directory, "status", "--porcelain"):
            raise ValueError(f"dependency checkout has local changes: {directory}")
        if git_output(directory, "rev-parse", "HEAD") != commit:
            raise ValueError(
                f"dependency revision differs: {directory}; choose a new --directory"
            )
        return
    directory.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "init", "--quiet", str(directory)], check=True)
    subprocess.run(
        ["git", "-C", str(directory), "remote", "add", "origin", url], check=True
    )
    command = ["git", "-C", str(directory)]
    if url.startswith("https://github.com/"):
        # GLEIF repositories require access. Use gh for this command only;
        # credentials remain in the existing account/keychain configuration.
        command += [
            "-c",
            "credential.helper=",
            "-c",
            "credential.helper=!gh auth git-credential",
        ]
    subprocess.run([*command, "fetch", "--depth=1", "origin", commit], check=True)
    subprocess.run(
        ["git", "-C", str(directory), "checkout", "--detach", commit], check=True
    )
    if git_output(directory, "rev-parse", "HEAD") != commit:
        raise ValueError(f"dependency commit did not resolve exactly: {directory}")


def write_environment(path: Path, values: dict[str, str]) -> None:
    """Write shell-safe exports, including checkout paths that contain spaces."""
    lines = [
        "# Generated by prepare-demo.py; source this file before running demo scripts."
    ]
    lines.extend(
        f"export {name}={shlex.quote(value)}" for name, value in values.items()
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def prepare_python_environment(directory: Path) -> Path:
    """Create a venv whose interpreter still resolves its platform libraries.

    macOS standalone Python uses paths relative to the executable for libpython;
    copying that executable into the venv breaks them. Symlinks retain the
    installed interpreter's library relationship on supported POSIX platforms.
    """
    # Resolve launcher links so pyvenv.cfg names the actual installation,
    # rather than a generic bin directory that has no Python standard library.
    interpreter = Path(sys.executable).resolve()
    subprocess.run(
        [str(interpreter), "-m", "venv", "--symlinks", str(directory)], check=True
    )
    python = directory / "bin" / "python"
    # The upstream and GLEIF distributions install the same import paths.
    # Reusing an upstream environment would leave ambiguous package ownership.
    installed = subprocess.check_output(
        [
            str(python),
            "-c",
            (
                "from importlib.metadata import distributions; "
                "print(' '.join(d.metadata['Name'].lower() for d in distributions()))"
            ),
        ],
        text=True,
    ).split()
    if {"keri", "hio"}.intersection(installed):
        raise ValueError(
            "upstream keri/hio found; choose a fresh --directory for GLEIF packages"
        )
    return python


def copy_oracle_source(source: Path, destination: Path) -> None:
    """Build only current package inputs, excluding stale local build products."""
    for filename in ("pyproject.toml", "README.md"):
        shutil.copy2(source / filename, destination / filename)
    shutil.copytree(source / "src", destination / "src",
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "*.egg-info"))


def main() -> None:
    """Prepare the selected dependency checkouts and, for a full demo, its environment."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--directory",
        type=Path,
        default=ORACLE_ROOT / ".demo",
        help="dependency/environment directory (default: this checkout's .demo)",
    )
    parser.add_argument(
        "--schemas-only",
        action="store_true",
        help="prepare only the pinned vLEI schemas for the association HTTP exercise",
    )
    args = parser.parse_args()
    if sys.version_info < (3, 12, 6):
        parser.error("Python 3.12.6 or newer is required by the pinned vLEI package")
    directory = args.directory.expanduser().resolve()
    dependencies = json.loads(DEPENDENCY_MANIFEST.read_text())
    if args.schemas_only:
        dependencies = {"vLEI": dependencies["vLEI"]}
    checkouts = {name: directory / "checkouts" / name for name in dependencies}
    for name, dependency in dependencies.items():
        prepare_checkout(
            checkouts[name], url=dependency["url"], commit=dependency["commit"]
        )
    if args.schemas_only:
        print(f"Schemas prepared: {checkouts['vLEI'] / 'schema/acdc'}")
        return
    subprocess.run(
        [
            "git",
            "-C",
            str(checkouts["vlei-comply"]),
            "submodule",
            "update",
            "--init",
            "--recursive",
            "--depth=1",
        ],
        check=True,
    )
    environment = directory / "venv"
    python = prepare_python_environment(environment)
    vlei = dependencies["vLEI"]
    # setuptools can retain removed modules in a reused build/lib directory.
    # Copy current inputs into a fresh build root without deleting local artifacts.
    with TemporaryDirectory(prefix="vlei-oracle-build-") as build_root:
        copy_oracle_source(ORACLE_ROOT, Path(build_root))
        subprocess.run(
            [str(python), "-m", "pip", "install", build_root + "[dev]",
             "-r", str(Path(__file__).with_name("demo-requirements.txt"))],
            check=True,
        )
    # vLEI's metadata still names upstream keri/hio. Install its schema tools
    # without resolving those names; demo-requirements supplies the dependencies.
    subprocess.run(
        [
            str(python),
            "-m",
            "pip",
            "install",
            "--no-deps",
            f"vlei @ git+{vlei['url']}@{vlei['commit']}",
        ],
        check=True,
    )
    bin_dir = environment / "bin"
    path = directory / "demo.env"
    write_environment(
        path,
        {
            "DEMO_ENV": str(path),
            "ORACLE_DIR": str(ORACLE_ROOT),
            "COMPLY_DIR": str(checkouts["vlei-comply"]),
            "KERIPY_DIR": str(checkouts["keripy"]),
            "VLEI_SCHEMA_TOOLS_DIR": str(checkouts["vLEI"]),
            "KLI": str(bin_dir / "kli"),
            "VLEI_SERVER": str(bin_dir / "vLEI-server"),
            "VLEI_ORACLE": str(bin_dir / "vlei-oracle"),
        },
    )
    print(f"Dependencies prepared. Load exports with: source {shlex.quote(str(path))}")
    print("Preparation did not start services, deploy contracts, or touch KERI stores.")


if __name__ == "__main__":
    main()
